"""Generate the technical solution report (.docx) for the LGL-Lab AIC entry.

Methodology document: no compliance-audit chapter and no leaderboard scores.
Covers the method in full -- LoRA and the rank axis, the qkv placement, the
attention modules (per-head temperature, pooling attention, local head), the
automatic noise governance, image-side filtering, the training objective, the
data strategy, inference, reproducibility, and the recorded candidate pool.

Prose carries the argument. Only three tables are used, each genuinely tabular:
parameter accounting, the noise decision rule, and the core parameter defaults.

Every mechanism claim was reconciled against the current code; where the
project's own documents describe flags that no longer exist (or flag names that
were later renamed), the code wins and the report states the code's behaviour.

Usage::

    <python> generate_tech_report.py --output 技术方案报告.docx
"""
import argparse

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

BODY_FONT = 'SimSun'
HEAD_FONT = 'SimHei'
MONO_FONT = 'Consolas'
EA_FONT = '宋体'
EA_HEAD_FONT = '黑体'

PORTRAIT_W, LANDSCAPE_W = 21.0, 29.7
MARGIN = 2.3


def _style_run(run, font, size=None, bold=None, color=None):
    run.font.name = font
    run._element.rPr.rFonts.set(qn('w:eastAsia'), EA_HEAD_FONT if font == HEAD_FONT else EA_FONT)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def title(doc, text, sub=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(2)
    _style_run(p.add_run(text), HEAD_FONT, size=19, bold=True)
    if sub:
        q = doc.add_paragraph()
        q.alignment = WD_ALIGN_PARAGRAPH.CENTER
        q.paragraph_format.space_after = Pt(10)
        _style_run(q.add_run(sub), BODY_FONT, size=10, color=RGBColor(0x59, 0x59, 0x59))


def h(doc, text, level=1):
    p = doc.add_heading(level=level)
    p.paragraph_format.space_before = Pt(12 if level == 1 else 9)
    p.paragraph_format.space_after = Pt(4)
    _style_run(p.add_run(text), HEAD_FONT, size=15 - level, bold=True,
               color=RGBColor(0x1F, 0x3B, 0x63))


def para(doc, text, size=10.5, indent=True, space_after=5):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.28
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    _style_run(p.add_run(text), BODY_FONT, size=size)
    return p


def rich(doc, parts, size=10.5, indent=True):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(5)
    p.paragraph_format.line_spacing = 1.28
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    for text, bold in parts:
        _style_run(p.add_run(text), BODY_FONT, size=size, bold=bold)
    return p


def code(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(1.0)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.12
    _style_run(p.add_run(text), MONO_FONT, size=8.5)


def bullet(doc, text, size=10.5):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.22
    _style_run(p.add_run(text), BODY_FONT, size=size)
    return p


def _fixed_layout(t):
    tblPr = t._tbl.tblPr
    for tag in ('w:tblLayout', 'w:tblW'):
        for el in tblPr.findall(qn(tag)):
            tblPr.remove(el)
    tblPr.append(tblPr.makeelement(qn('w:tblLayout'), {qn('w:type'): 'fixed'}))


def table(doc, header, rows, widths, size=9.5):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, txt in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ''
        _style_run(c.paragraphs[0].add_run(txt), HEAD_FONT, size=size, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, txt in enumerate(row):
            cells[i].text = ''
            _style_run(cells[i].paragraphs[0].add_run(str(txt)), BODY_FONT, size=size)
    if sum(widths) > PORTRAIT_W - 2 * MARGIN + 0.05:
        raise ValueError(f'table widths {sum(widths):.1f}cm exceed text column')
    for r in t.rows:
        for i, w in enumerate(widths):
            r.cells[i].width = Cm(w)
    _fixed_layout(t)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


