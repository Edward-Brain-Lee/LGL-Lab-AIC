    h(doc, '五、数据策略与增强')

    para(doc, '数据侧的关键设计有五条。')
    para(doc, '第一，分层切分留出集。按类内部比例留出验证样本，保证每个类都有代表。'
              '这里有一个曾经真实存在的缺陷值得记录——验证集的切分规模一度依赖于'
              '「当前正在构建哪个 split」，导致训练集静默吞掉整个验证集；'
              '修正后切分规模只由留出比例与类内样本数决定，自检断言训练集与验证集无交集且并集为全集。'
              '另需注明，当前实现即使把留出比例设为零，仍会为每类保留样本，'
              '因此「全量数据复训」尚未真正实现，需要先处理空留出集时的评估逻辑；'
              '并且不能把全量训练出来的模型再拿回原留出集上排名。'
              '切分种子与优化种子已解耦：所有候选固定同一个切分种子，'
              '换优化种子时不改变「考卷」，从而让种子对照成为真正的重复验证。')
    para(doc, '第二，读图容错。官方提示部分图片文件可能被截断、在文件系统中显示异常，'
              '但都能被 Pillow 正常读取。训练端读不出的图以灰色图兜底而不跳过，'
              '推理端同理——因为跳过任何一张图都会导致提交文件行数少于测试集规模，提交直接判无效。'
              '这是必须防住的工程细节，属于「不报错但结果作废」的类型。')
    para(doc, '第三，采样策略。默认使用按类频次倒数平方根加权的平衡采样，'
              '这是为后续阶段可能出现的长尾分布做的准备，本阶段它只是温和修正。'
              '这里有两个必须记录的认识。其一，当前加权采样与均匀采样都是有放回的，'
              '长度 N 的有放回采样每轮期望只覆盖约 63% 的样本，'
              '在纯交叉熵阶段这会明显影响原型初始化与教师信号的覆盖度，'
              '尾类反复看到同一张图的问题也更突出；实测中未被观察样本的比例与这一估算吻合。'
              '其二，这类改动存在变量混淆：从平衡采样切到无放回采样会同时移除频次均衡'
              '与重复曝光两个机制，要单独归因「是否有放回」，需要另设一组对照。'
              '因此方案要求在实际运行中输出每类的有效曝光量与降权比例，而不能只看整体准确率。'
              '一个更严重的连带问题是：未被采样到的样本在首次判定时保留原标签、权重为满值，'
              '即使其中有错标也不会被教师筛选；而现有存档在训练结束后已无法倒推出'
              '阶段切换时的未见名单，因此需要在新训练中单独保存该掩码。')
    para(doc, '第四，增强。训练使用随机尺寸裁剪（裁剪比例下界 0.55）、水平翻转与 RandAugment，'
              '并对同一张图做两次独立增强以供一致性正则使用；'
              '归一化使用 CLIP 自己的均值与方差而不是 ImageNet 的。'
              '增强强度是两个独立可调参数，也是后续「治过拟合」这条主线的核心旋钮。'
              '这里有一个必须警惕的耦合：教师判噪所依据的视图，本身也是经过强增强的视图，'
              '因此当增强幅度改变时，被裁掉的判别线索或被扰动的颜色会让判噪判据一并改变。'
              '换句话说，增强不只是影响学生泛化，它同时改变了筛选目标，'
              '这使「加强增强」不能被简单假定为只会带来收益。'
              '后续据此提出的一项改进是为教师另提供一路弱增强视图（学生两视图不变，'
              '教师仍只做一次前向），从而把「增强强度」与「判噪判据」解耦；'
              '该改动尚未实现。')
    para(doc, '第五，增强的确定性。这既关乎可复现性，也曾经是一个隐性缺陷。'
              '早期实现中图像增强是从该数据加载进程自己的随机数发生器取随机数的，'
              '于是「哪张图被哪个进程取到」决定了它被如何增强，而这个映射随进程数变化。'
              '每种进程数都能正常训练、正常收敛，只是收敛到不同结果，故障因此完全不可见——'
              '唯一的症状是「提交的代码复现不出提交的分数」。'
              '修正后增强成为纯函数，由（种子、样本索引、视图编号）派生，与进程数无关；'
              '自检中新增断言，要求同一样本在不同进程数下逐位相同，'
              '且同一张图的两个视图必须不同（否则一致性损失等于拿一张图和自己比）。'
              '这一改动也带来一个副作用：由于增强种子不含轮次，'
              '同一张训练图在不同轮次看到的是两张固定增强图，可能在 20 轮训练中降低增强多样性。'
              '把轮次纳入种子被列为低成本候选，但它同时会改变筛选目标，需要独立实验验证。')

